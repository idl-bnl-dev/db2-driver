<?php

use BWICompanies\DB2Driver\Schema\DB2Blueprint;

function schemaSql(string $table, Closure $callback, ?\BWICompanies\DB2Driver\DB2Connection $connection = null): array
{
    $connection ??= db2();

    return (new DB2Blueprint($connection, $table, $callback))->toSql();
}

it('compiles create table with identity primary key', function () {
    $sql = schemaSql('users', function ($table) {
        $table->create();
        $table->id();
        $table->string('name', 50);
        $table->integer('age')->nullable();
        $table->timestamps();
    });

    expect($sql)->toBe([
        'create table users (id bigint not null generated by default as identity constraint users_id_primary primary key, name varchar(50) not null, age int, created_at timestamp, updated_at timestamp)',
    ]);
});

it('adds a system name to create table', function () {
    $sql = schemaSql('mylib.orders', function ($table) {
        $table->create();
        $table->forSystemName('ORDERS');
        $table->integer('id');
    });

    expect($sql[0])->toBe('create table mylib.orders for system name ORDERS (id int not null)');
});

it('compiles column types', function (string $method, array $args, string $expected) {
    $sql = schemaSql('t', fn ($table) => $table->{$method}('c', ...$args)->nullable());

    expect($sql[0])->toBe("alter table t add c {$expected}");
})->with([
    'string' => ['string', [20], 'varchar(20)'],
    'char' => ['char', [3], 'char(3)'],
    'integer' => ['integer', [], 'int'],
    'bigInteger' => ['bigInteger', [], 'bigint'],
    'smallInteger' => ['smallInteger', [], 'smallint'],
    'decimal' => ['decimal', [10, 2], 'decimal(10, 2)'],
    'numeric' => ['numeric', [8, 2], 'numeric(8, 2)'],
    'text' => ['text', [], 'clob(64K)'],
    'date' => ['date', [], 'date'],
    'uuid' => ['uuid', [], 'char(36)'],
]);

it('compiles booleans as smallint with a check constraint', function () {
    $sql = schemaSql('users', fn ($table) => $table->boolean('active')->default(true));

    expect($sql[0])->toContain('active smallint constraint boolean_users_active check(active in(0, 1))')
        ->toContain('default 1');
});

it('drops the schema from the boolean constraint name', function () {
    $sql = schemaSql('mylib.users', fn ($table) => $table->boolean('active'));

    expect($sql[0])->toContain('constraint boolean_users_active check');
});

it('compiles a unique constraint', function () {
    $sql = schemaSql('users', fn ($table) => $table->unique('email'));

    expect($sql)->toBe(['alter table users add constraint users_email_unique unique(email)']);
});

it('compiles an index', function () {
    $sql = schemaSql('mylib.orders', fn ($table) => $table->index('d'));

    expect($sql)->toBe(['create index orders_d_index on mylib.orders(d)']);
});

it('compiles a primary key', function () {
    $sql = schemaSql('mylib.orders', fn ($table) => $table->primary('id'));

    expect($sql)->toBe(['alter table mylib.orders add constraint orders_id_primary primary key (id)']);
});

it('compiles a foreign key with actions', function () {
    $sql = schemaSql('orders', fn ($table) => $table->foreign('user_id')->references('id')->on('users')->onDelete('cascade'));

    expect($sql)->toBe([
        'alter table orders add constraint orders_user_id_foreign foreign key (user_id) references users (id) on delete cascade',
    ]);
});

it('compiles a table label', function () {
    $sql = schemaSql('orders', fn ($table) => $table->label('Customer orders'));

    expect($sql)->toBe(["label on table orders is 'Customer orders'"]);
});

it('compiles drop and rename table', function () {
    expect(schemaSql('users', fn ($t) => $t->drop()))->toBe(['drop table users'])
        ->and(schemaSql('users', fn ($t) => $t->dropIfExists()))->toBe(['drop table if exists users'])
        ->and(schemaSql('users', fn ($t) => $t->rename('people')))->toBe(['rename table users to people']);
});

it('drops primary keys and foreign keys', function () {
    expect(schemaSql('users', fn ($t) => $t->dropPrimary('p')))->toBe(['alter table users drop primary key'])
        ->and(schemaSql('users', fn ($t) => $t->dropForeign('f')))->toBe(['alter table users drop foreign key f']);
});

it('wraps drop column in a reply list entry on IBM i', function () {
    $connection = db2();
    $connection->selectResults = [[(object) ['sequence_number' => 7]]];

    $sql = schemaSql('users', fn ($table) => $table->dropColumn('age'), $connection);

    expect($sql)->toBe([
        "CALL QSYS2.QCMDEXC('ADDRPYLE SEQNBR(7) MSGID(CPA32B2) RPY(''I'')')",
        "CALL QSYS2.QCMDEXC('CHGJOB INQMSGRPY(*SYSRPYL)')",
        'alter table users drop age',
        "CALL QSYS2.QCMDEXC('RMVRPYLE SEQNBR(7)')",
    ]);
});

it('has table/column existence queries bound to schema and table', function () {
    $grammar = db2()->getSchemaGrammar();

    expect($grammar->compileTableExists('mylib', 'users'))
        ->toBe("select * from information_schema.tables where table_schema = upper('mylib') and table_name = upper('users')")
        ->and($grammar->compileColumnExists())
        ->toBe('select column_name from information_schema.columns where table_schema = upper(?) and table_name = upper(?)');
});

it('checks table existence using the default schema and prefix', function () {
    $connection = db2(['prefix' => 'p_']);
    $connection->selectResults = [[(object) ['table_name' => 'P_USERS']]];

    expect($connection->getSchemaBuilder()->hasTable('users'))->toBeTrue()
        ->and($connection->selects[0]['query'])->toContain("table_schema = upper('TESTLIB') and table_name = upper('p_users')");
});

it('checks table existence with an explicit schema', function () {
    $connection = db2();

    expect($connection->getSchemaBuilder()->hasTable('other.users'))->toBeFalse()
        ->and($connection->selects[0]['query'])->toContain("table_schema = upper('other') and table_name = upper('users')");
});

it('switches schema while building a schema-qualified table', function () {
    $connection = db2();
    $connection->getSchemaBuilder()->create('mylib.t', function ($table) {
        $table->integer('id');
    });

    $schemaCalls = array_column($connection->statements, 'bindings');

    expect($schemaCalls[0])->toBe(['MYLIB'])
        ->and(end($schemaCalls))->toBe(['TESTLIB']);
});
